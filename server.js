/**
 * ============================================================================
 * BRAINTREE DEMO SUITE — SERVER
 * ============================================================================
 *
 * WHY DOES THIS SERVER EXIST AT ALL?
 * -----------------------------------
 * Braintree's architecture is split into two trust zones, and this file is
 * the entire "server-side" half of that split:
 *
 *   1. SERVER-SIDE (this file) — holds the PRIVATE KEY. The private key can
 *      authorize real money movement (sales, refunds, voids). It must never
 *      be sent to a browser, embedded in frontend JS, or committed to a
 *      public repo. Every operation that touches the private key happens
 *      here, on infrastructure you control.
 *
 *   2. CLIENT-SIDE (everything in /public) — holds only a CLIENT TOKEN, a
 *      short-lived, scoped-down credential generated BY the server FOR one
 *      browser session. A client token can tokenize a payment method (turn
 *      a card/PayPal login/etc. into a one-time-use "nonce"), but it cannot
 *      move money on its own. This is what makes it safe to put in a browser.
 *
 * This client-token / nonce split is the single most important concept in
 * Braintree's integration model — nearly everything else in this codebase
 * exists to demonstrate it.
 * ============================================================================
 */

require('dotenv').config();
const express = require('express');
const cors = require('cors');
const braintree = require('braintree');
const path = require('path');

const app = express();
app.use(cors());
app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

const vaultedCustomers = [];

function buildGateway({ merchantId, publicKey, privateKey, environment } = {}) {
  const env = (environment || process.env.BT_ENVIRONMENT || 'Sandbox').toLowerCase() === 'production'
    ? braintree.Environment.Production
    : braintree.Environment.Sandbox;

  return new braintree.BraintreeGateway({
    environment: env,
    merchantId: merchantId || process.env.BT_MERCHANT_ID,
    publicKey: publicKey || process.env.BT_PUBLIC_KEY,
    privateKey: privateKey || process.env.BT_PRIVATE_KEY,
  });
}

app.post('/api/client-token', async (req, res) => {
  try {
    const gateway = buildGateway(req.body || {});
    const response = await gateway.clientToken.generate({});
    res.json({
      success: true,
      clientToken: response.clientToken,
      raw: response,
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      error: err.message,
      raw: err,
    });
  }
});

// >>> STEP:checkout
app.post('/api/checkout', async (req, res) => {
  const { paymentMethodNonce, amount, credentials, customer, billingAddress, saveInVault } = req.body;

  if (!paymentMethodNonce || !amount) {
    return res.status(400).json({
      success: false,
      error: 'paymentMethodNonce and amount are required',
    });
  }

  try {
    const gateway = buildGateway(credentials || {});

    const saleRequest = {
      amount: String(amount),
      paymentMethodNonce,
      options: {
        submitForSettlement: true,
      },
    };

    if (customer && (customer.firstName || customer.lastName || customer.email)) {
      saleRequest.customer = {
        firstName: customer.firstName || undefined,
        lastName: customer.lastName || undefined,
        email: customer.email || undefined,
      };
    }

    if (billingAddress && billingAddress.streetAddress) {
      saleRequest.billing = {
        streetAddress: billingAddress.streetAddress || undefined,
        locality: billingAddress.locality || undefined,
        region: billingAddress.region || undefined,
        postalCode: billingAddress.postalCode || undefined,
        countryCodeAlpha2: billingAddress.countryCodeAlpha2 || undefined,
      };
    }

    if (saveInVault) {
      saleRequest.options.storeInVaultOnSuccess = true;
    }

    const result = await gateway.transaction.sale(saleRequest);

    if (result.success && saveInVault && result.transaction.customer && result.transaction.paymentMethodToken) {
      vaultedCustomers.push({
        customerId: result.transaction.customer.id,
        paymentMethodToken: result.transaction.paymentMethodToken,
        label: `${result.transaction.customer.firstName || ''} ${result.transaction.customer.lastName || ''}`.trim()
          || result.transaction.customer.email
          || result.transaction.customer.id,
        paymentInstrumentType: result.transaction.paymentInstrumentType,
        vaultedAt: new Date().toISOString(),
        source: 'checkout-with-vault',
      });
    }

    res.json({
      success: result.success,
      transaction: result.success ? result.transaction : null,
      message: result.message,
      raw: result,
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      error: err.message,
      raw: err,
    });
  }
});
// <<< STEP:checkout


// >>> STEP:vaultstore
app.post('/api/vault/store', async (req, res) => {
  const { paymentMethodNonce, customer, credentials, usBankAccountVerificationMethod } = req.body;

  if (!paymentMethodNonce) {
    return res.status(400).json({
      success: false,
      error: 'paymentMethodNonce is required',
    });
  }

  try {
    const gateway = buildGateway(credentials || {});

    // ---------------------------------------------------------------------
    // Card vaulting (no verification method): customer.create() combined
    // with paymentMethodNonce in one call works fine — this is Braintree's
    // normal "create customer + attach payment method" shortcut.
    //
    // ACH vaulting (usBankAccountVerificationMethod present): that option
    // is ONLY valid on paymentMethod.create() with an existing customerId —
    // it is not a valid key inside customer.create(), even combined with a
    // nonce. Passing it there fails the same way options[usBankAccountVerificationMethod]
    // failed on transaction.sale() in /api/ach/charge. So for ACH we split
    // this into two calls: create a bare customer first, then vault +
    // verify the bank account against that customerId.
    // ---------------------------------------------------------------------
    let result;

    if (usBankAccountVerificationMethod) {
      const customerResult = await gateway.customer.create({
        firstName: customer?.firstName || undefined,
        lastName: customer?.lastName || undefined,
        email: customer?.email || undefined,
      });

      if (!customerResult.success) {
        return res.status(402).json({
          success: false,
          error: customerResult.message,
          raw: customerResult,
        });
      }

      const paymentMethodResult = await gateway.paymentMethod.create({
        customerId: customerResult.customer.id,
        paymentMethodNonce,
        options: {
          usBankAccountVerificationMethod,
        },
      });

      // Reshape to look like a customer.create() result below, so the rest
      // of this handler (and the frontend) doesn't need two code paths.
      result = {
        success: paymentMethodResult.success,
        message: paymentMethodResult.message,
        customer: paymentMethodResult.success
          ? { ...customerResult.customer, paymentMethods: [paymentMethodResult.paymentMethod] }
          : null,
        raw: { customerResult, paymentMethodResult },
      };
    } else {
      const customerRequest = {
        paymentMethodNonce,
      };
      if (customer && (customer.firstName || customer.lastName || customer.email)) {
        customerRequest.firstName = customer.firstName || undefined;
        customerRequest.lastName = customer.lastName || undefined;
        customerRequest.email = customer.email || undefined;
      }

      result = await gateway.customer.create(customerRequest);
    }

    if (result.success) {
      const paymentMethods = result.customer.paymentMethods || [];
      const primaryMethod = paymentMethods[0];

      vaultedCustomers.push({
        customerId: result.customer.id,
        paymentMethodToken: primaryMethod ? primaryMethod.token : null,
        label: `${result.customer.firstName || ''} ${result.customer.lastName || ''}`.trim()
          || result.customer.email
          || result.customer.id,
        paymentInstrumentType: primaryMethod ? primaryMethod.constructor?.name : 'unknown',
        vaultedAt: new Date().toISOString(),
        source: 'vault-store',
      });
    }

    res.json({
      success: result.success,
      customer: result.success ? result.customer : null,
      message: result.message,
      raw: result.raw || result,
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      error: err.message,
      raw: err,
    });
  }
});
