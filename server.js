// ---------------------------------------------------------------------------
// POST /api/ach/charge
// ---------------------------------------------------------------------------
// ACH DOESN'T FOLLOW THE SAME ONE-CALL PATTERN AS CARD/PAYPAL/VENMO.
//
// Every other payment method in this demo takes a nonce straight into
// transaction.sale() and that's the whole story. ACH can't do that, because
// usBankAccountVerificationMethod is not a valid transaction.sale() option —
// Braintree only accepts it on paymentMethod.create(). Passing it to
// transaction.sale() (as this endpoint used to) fails immediately with:
//   invalidKeysError: "These keys are invalid: options[usBankAccountVerificationMethod]"
//
// The actual required flow is Braintree's "verify-then-charge" pattern, and
// it's genuinely two separate API calls:
//
//   1. paymentMethod.create() — vaults the bank account nonce AND runs the
//      requested verification (network check here). This step needs a
//      customerId, because ACH verification is tied to a customer record,
//      not a bare nonce. Returns a paymentMethodToken once vaulted.
//
//   2. transaction.sale() — charges that verified paymentMethodToken. No
//      verification option belongs here at all; verification already
//      happened in step 1.
//
// This is different from Card/PayPal, where a single transaction.sale() can
// tokenize-and-charge in one call — ACH's verification requirement forces
// the split.
// ---------------------------------------------------------------------------
// >>> STEP:achcharge
app.post('/api/ach/charge', async (req, res) => {
  const { paymentMethodNonce, amount, customer, credentials } = req.body;

  if (!paymentMethodNonce || !amount) {
    return res.status(400).json({
      success: false,
      error: 'paymentMethodNonce and amount are required',
    });
  }

  try {
    const gateway = buildGateway(credentials || {});

    // Step 0: ACH verification needs a customer record to attach to. Create
    // a lightweight one here rather than requiring the caller to manage
    // customer IDs — fine for a demo; a real integration would likely reuse
    // an existing logged-in customer's ID instead of minting a new one per
    // charge.
    const customerResult = await gateway.customer.create({
      firstName: customer?.firstName || undefined,
      lastName: customer?.lastName || undefined,
      email: customer?.email || undefined,
    });

    if (!customerResult.success) {
      return res.status(402).json({
        success: false,
        error: customerResult.message,
        raw: customerResult,
      });
    }

    // Step 1: Vault + verify the bank account. This is the ONLY place
    // usBankAccountVerificationMethod is a valid option.
    const paymentMethodResult = await gateway.paymentMethod.create({
      customerId: customerResult.customer.id,
      paymentMethodNonce,
      options: {
        usBankAccountVerificationMethod: 'network_check',
      },
    });

    if (!paymentMethodResult.success) {
      return res.status(402).json({
        success: false,
        error: paymentMethodResult.message,
        raw: paymentMethodResult,
      });
    }

    const verifiedToken = paymentMethodResult.usBankAccount?.token
      || paymentMethodResult.paymentMethod?.token;

    // Step 2: Charge the now-verified payment method. No verification
    // option here — that already happened in Step 1.
    const result = await gateway.transaction.sale({
      amount: String(amount),
      paymentMethodToken: verifiedToken,
      options: {
        submitForSettlement: true,
      },
    });

    res.json({
      success: result.success,
      transaction: result.success ? result.transaction : null,
      message: result.message,
      raw: { customerResult, paymentMethodResult, saleResult: result },
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      error: err.message,
      raw: err,
    });
  }
});
// <<< STEP:achcharge

